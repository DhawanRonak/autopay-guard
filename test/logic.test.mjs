import { createRequire } from 'module';
import assert from 'node:assert/strict';
const G=createRequire(import.meta.url)('../logic.js');
let list=G.seed();
assert.ok(G.validList(list));
assert.equal(G.monthlyTotal(list),Math.round(299+119+99+130+1499+999/12+5000+8400/12+1840+799+49*52/12));
assert.deepEqual(G.insights(list).map(i=>i.kind+':'+i.id),['trial_ending:6','price_hike:1','big_annual:8','high_ceiling:10','duplicate:3']);
assert.deepEqual(G.upcoming(list,7).map(m=>m.id),[5,6,1,11,7]);
const before=G.monthlyTotal(list);list=G.actions.cancel(list,3);
assert.equal(G.monthlyTotal(list),before-99);assert.ok(!G.insights(list).some(i=>i.kind==='duplicate'));
list=G.actions.pause(list,5,1);assert.equal(list.find(m=>m.id===5).resumeInDays,31);
list=G.actions.resume(list,5);assert.equal(list.find(m=>m.id===5).nextInDays,1,'Resuming early restores original next charge');
list=G.actions.lowerCeiling(list,10);assert.ok(!G.insights(list).some(i=>i.kind==='high_ceiling'));
const old=list;list=G.actions.remind(list,8,3);assert.equal(old.find(m=>m.id===8).reminderDays,1);assert.ok(G.TASKS[3].done(list,[]));
for(const action of ['pause','resume','cancel','remind','lowerCeiling'])assert.throws(()=>G.actions[action](list,999,1),/not found/);
for(const cycles of [0,4,1.5,'1',NaN])assert.throws(()=>G.actions.pause(G.seed(),5,cycles));
for(const days of [0,2,8,'3'])assert.throws(()=>G.actions.remind(G.seed(),8,days));
assert.throws(()=>G.actions.resume(G.seed(),1));
assert.throws(()=>G.actions.cancel(G.actions.cancel(G.seed(),1),1));
assert.throws(()=>G.actions.lowerCeiling(G.seed(),9),'Variable bill limit must not be lowered');
assert.ok(!G.validList([{...G.seed()[0],freq:'bad'}]));assert.ok(!G.validList([null]));assert.ok(!G.validList([...G.seed(),G.seed()[0]]));assert.ok(G.validList([]));
const fixture=patch=>[{...G.seed()[0],trial:null,prevAmount:100,amount:110,maxAmount:110,...patch}];
assert.ok(G.insights(fixture({})).some(i=>i.kind==='price_hike'),'Exactly 10 percent increase');
assert.ok(!G.insights(fixture({amount:109.99})).some(i=>i.kind==='price_hike'));
assert.ok(!G.insights(fixture({prevAmount:0})).some(i=>i.kind==='price_hike'));
assert.match(G.insights(fixture({freq:'weekly'}))[0].body,/520 more a year/);
assert.match(G.insights(fixture({freq:'quarterly'}))[0].body,/40 more a year/);
assert.ok(!G.insights(fixture({variable:true})).some(i=>i.kind==='price_hike'));
assert.ok(G.insights(fixture({maxAmount:550})).some(i=>i.kind==='high_ceiling'));
assert.ok(!G.insights(fixture({maxAmount:549})).some(i=>i.kind==='high_ceiling'));
assert.ok(G.insights(fixture({freq:'yearly',amount:1000,maxAmount:1000,nextInDays:30})).some(i=>i.kind==='big_annual'));
assert.ok(!G.insights(fixture({freq:'yearly',amount:1000,nextInDays:31})).some(i=>i.kind==='big_annual'));
assert.ok(!G.insights(fixture({trial:{paid:1},nextInDays:4})).some(i=>i.kind==='trial_ending'));
assert.equal(G.dueTotal(fixture({freq:'weekly',amount:100,nextInDays:0}),7),200,'Both today and day seven are charged');
assert.equal(G.dueTotal(fixture({nextInDays:-1}),7),0,'Overdue relative date excluded');
let paused=G.actions.pause(G.seed(),5,1);paused=G.advance(paused,10);assert.equal(paused.find(m=>m.id===5).resumeInDays,21);assert.equal(paused.find(m=>m.id===5).status,'paused');
paused=G.advance(paused,21);assert.equal(paused.find(m=>m.id===5).status,'active');assert.equal(paused.find(m=>m.id===5).nextInDays,0);
assert.equal(G.advance(fixture({nextInDays:1,freq:'weekly'}),9)[0].nextInDays,6);
assert.equal(G.advance(G.seed(),3).find(m=>m.id===6).trial,null);
assert.ok(!G.TASKS[2].done(G.actions.pause(G.seed(),5,2),[]));assert.ok(!G.TASKS[1].done([],[]));
assert.equal(G.seed()[0].status,'active');
console.log('Autopay Guard: all logic and rule-boundary tests passed');
